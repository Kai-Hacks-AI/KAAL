// hosting/T260 and hosting/T261: the portability audit follows a registration function bound to a local name.
//
// hosting/T260 is the RED Case of hosting/D16: it fails on 2e45a5e (Hosting 0.0.1 on main, where a registration through a
// platform-dependent local name is not attributed) and must pass, unmodified, in the Change that fixes it. hosting/T261 is
// a control that passes before and after. The Cases drive the real `portability` from the built package on a capability
// written to a temporary directory. `const run = process.platform === "win32" ? it.skip : it` registers `run("…")` as a
// skipped case on one host and a live one on the other, so Testing must not count it as evidence on every host.
//
// This file is RED by design. No suite, lane or script names it, so required CI does not run it; run it by hand:
//
//   npm run build -w @kaihacksai/kaal-hosting
//   node --test packages/kaal-hosting/06-defects/local-registration.red.mjs
//
// hosting/D16 is answered when hosting/T260 passes, unmodified, with hosting/T261 still passing.
// Do not edit this file to pass.
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { portability } from "../dist/skills/kaal-hosting/scripts/boundary-core.js";

/** The `challenged` cases of `portability` over one test source in a temporary capability. */
async function challenged(body) {
  const root = mkdtempSync(join(tmpdir(), "hosting-d16-"));
  try {
    mkdirSync(join(root, "test"));
    writeFileSync(join(root, "package.json"), JSON.stringify({ name: "capability", version: "1.0.0" }));
    writeFileSync(join(root, "test", "a.test.mjs"), `import { it } from "node:test";\n${body}\n`);
    return (await portability({ name: "capability", root, builtins: ["node:test"] })).challenged;
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

test("hosting/T260: a case registered through a platform-dependent local name is challenged", async () => {
  const r = await challenged("const run = process.platform === 'win32' ? it.skip : it;\nrun('platform-dependent', () => {});");
  assert.deepEqual(r, ["platform-dependent"]);
});

test("hosting/T261 control: a case registered through a local name that does not depend on the platform is not challenged", async () => {
  const r = await challenged("const run = it;\nrun('always', () => {});");
  assert.deepEqual(r, []);
});
