// hosting/T137 to hosting/T139: `couplings` and a platform query inside a function body written on one line.
//
// hosting/T137 and hosting/T138 are the RED Cases of hosting/D8. hosting/T139 is its control and passes today.
// The Cases drive the real `couplings` from the built package over one production source whose platform query is
// an ordinary call in a function body (hosting/F28: a query bound by import or destructuring is a finding wherever
// it is used). The body shares a line with the opening brace.
//
// This file is RED by design. No suite, lane or script names it, so required CI does not run it; run it by hand:
//
//   npm run build -w @kaihacksai/kaal-hosting
//   node --test packages/kaal-hosting/06-defects/one-line-function-body.red.mjs
//
// hosting/D8 is answered when hosting/T137 and hosting/T138 pass, unmodified, in the Change that fixes
// `couplings.ts`, with hosting/T139 still passing. Do not edit this file to pass.
import assert from "node:assert/strict";
import { test } from "node:test";
import { couplings } from "../dist/skills/kaal-hosting/scripts/couplings.js";

/** The production findings `couplings` reports for one source file. */
async function found(file, source) {
  const r = await couplings({ [file]: source });
  return r.findings.filter((f) => f.scope === "production" && (f.rule === "platform-query" || f.rule === "host-api"));
}

test("hosting/T139 control: the same call on its own line is a finding", async () => {
  const r = await found("lib/a.mjs", 'import { platform as host } from "node:os";\nexport function currentPlatform() {\n  return host();\n}\n');
  assert.equal(r.length > 0, true);
});

test("hosting/T137 RED (hosting/D8): an ESM named-import query in a one-line function body is a finding", async () => {
  const r = await found("lib/a.mjs", 'import { platform as host } from "node:os";\nexport function currentPlatform() { return host(); }\n');
  assert.equal(r.length > 0, true, "the query is called in a function body but couplings reports nothing");
});

test("hosting/T138 RED (hosting/D8): a CommonJS destructured query in a one-line function body is a finding", async () => {
  const r = await found("lib/a.cjs", 'const { platform: host } = require("node:os");\nfunction currentPlatform() { return host(); }\nmodule.exports = { currentPlatform };\n');
  assert.equal(r.length > 0, true, "the query is called in a function body but couplings reports nothing");
});
