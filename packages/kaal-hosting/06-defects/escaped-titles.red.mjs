// hosting/T258 and hosting/T259: the portability audit names a challenged case by its title as the program sees it.
//
// hosting/T258 is the RED Case of hosting/D15: it fails on 2e45a5e (Hosting 0.0.1 on main, where `challenged` holds the
// source spelling of an escaped literal title) and must pass, unmodified, in the Change that fixes it. hosting/T259 is
// a control that passes before and after. The Cases drive the real `portability` from the built package on a capability
// written to a temporary directory.
//
// This file is RED by design. No suite, lane or script names it, so required CI does not run it; run it by hand:
//
//   npm run build -w @kaihacksai/kaal-hosting
//   node --test packages/kaal-hosting/06-defects/escaped-titles.red.mjs
//
// hosting/D15 is answered when hosting/T258 passes, unmodified, with hosting/T259 still passing.
// Do not edit this file to pass.
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { portability } from "../dist/skills/kaal-hosting/scripts/boundary-core.js";

/** The `challenged` cases of `portability` over one test source in a temporary capability. */
async function challenged(body) {
  const root = mkdtempSync(join(tmpdir(), "hosting-d15-"));
  try {
    mkdirSync(join(root, "test"));
    writeFileSync(join(root, "package.json"), JSON.stringify({ name: "capability", version: "1.0.0" }));
    writeFileSync(join(root, "test", "a.test.mjs"), `import { it, test } from "node:test";\n${body}\n`);
    return (await portability({ name: "capability", root, builtins: ["node:test"] })).challenged;
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

test("hosting/T258: a challenged case whose literal title is escaped is named by the title the program sees", async () => {
  const r = await challenged("test('can\\'t run', { skip: process.platform === 'win32' }, () => {});");
  assert.deepEqual(r, ["can't run"]);
});

test("hosting/T259 control: a challenged case whose title has no escape is named by that title", async () => {
  const r = await challenged("test('plain title', { skip: process.platform === 'win32' }, () => {});");
  assert.deepEqual(r, ["plain title"]);
});
