// hosting/T243 to hosting/T248: the portability audit follows a platform guard to the boundary it leaves.
//
// hosting/T243, hosting/T244, hosting/T246 and hosting/T247 are the RED Cases of hosting/D13 and hosting/D14: they fail
// on the head Codex reviewed (4d80a07, the D12 fix) and must pass, unmodified, in the Change that fixes them.
// hosting/T245 and hosting/T248 are controls that pass before and after. The Cases drive the real `portability` from
// the built package on a capability written to a temporary directory. A return leaves the function it is in, not the
// nearest block (hosting/D13); a throw or a process exit leaves the scope too, and its guard is a registration guard
// like a return (hosting/D14). Every case registered after it in that function never happens on that host, so Testing
// must not count those cases as evidence there (hosting/F29, hosting/F40).
//
// This file is RED by design. No suite, lane or script names it, so required CI does not run it; run it by hand:
//
//   npm run build -w @kaihacksai/kaal-hosting
//   node --test packages/kaal-hosting/06-defects/guard-scope.red.mjs
//
// hosting/D13 is answered when hosting/T243 and hosting/T244 pass, unmodified, with hosting/T245 still passing.
// hosting/D14 is answered when hosting/T246 and hosting/T247 pass, unmodified, with hosting/T248 still passing.
// Do not edit this file to pass.
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { portability } from "../dist/skills/kaal-hosting/scripts/boundary-core.js";

/** The `challenged` cases of `portability` over one test source in a temporary capability. */
async function challenged(body) {
  const root = mkdtempSync(join(tmpdir(), "hosting-d13-"));
  try {
    mkdirSync(join(root, "test"));
    writeFileSync(join(root, "package.json"), JSON.stringify({ name: "capability", version: "1.0.0" }));
    writeFileSync(join(root, "test", "a.test.mjs"), `import { describe, it } from "node:test";\n${body}\n`);
    return (await portability({ name: "capability", root, builtins: ["node:test"] })).challenged;
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

test("hosting/T243: a return guard inside a try block challenges the cases registered after the block", async () => {
  const r = await challenged('describe("suite", () => {\n  try {\n    if (process.platform === "win32") return;\n  } catch {}\n  it("after", () => {});\n});');
  assert.deepEqual(r, ["after"]);
});

test("hosting/T244: a return guard inside a bare block challenges the cases registered after the block", async () => {
  const r = await challenged('describe("suite", () => {\n  {\n    if (process.platform === "win32") return;\n  }\n  it("after", () => {});\n});');
  assert.deepEqual(r, ["after"]);
});

test("hosting/T245 control: a return guard in a block inside a case callback leaves only that case", async () => {
  const r = await challenged('describe("suite", () => {\n  it("a", () => {\n    {\n      if (process.platform === "win32") return;\n    }\n  });\n  it("b", () => {});\n});');
  assert.deepEqual(r, ["a"]);
});

test("hosting/T246: a platform guard that exits the process challenges the cases registered after it", async () => {
  const r = await challenged('describe("suite", () => {\n  if (process.platform === "win32") {\n    process.exit(0);\n  }\n  it("after", () => {});\n});');
  assert.deepEqual(r, ["after"]);
});

test("hosting/T247: a platform guard that throws challenges the cases registered after it", async () => {
  const r = await challenged('describe("suite", () => {\n  if (process.platform === "win32") throw new Error("unsupported");\n  it("after", () => {});\n});');
  assert.deepEqual(r, ["after"]);
});

test("hosting/T248 control: a platform guard that throws inside a try with a catch challenges nothing after it", async () => {
  const r = await challenged('describe("suite", () => {\n  try {\n    if (process.platform === "win32") throw new Error("unsupported");\n  } catch {}\n  it("after", () => {});\n});');
  assert.deepEqual(r, []);
});
