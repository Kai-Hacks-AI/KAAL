// hosting/T235 to hosting/T238: the portability audit challenges every case registered after a platform guard that leaves the scope.
//
// hosting/T235, hosting/T236 and hosting/T237 are the RED Cases of hosting/D12: they fail on the head Codex reviewed
// (1189f31, the D11 fix) and must pass, unmodified, in the Change that fixes `affected` in `boundary-core.ts`.
// hosting/T238 is a control that passes before and after. The Cases drive the real `portability` from the built
// package on a capability written to a temporary directory. A platform guard that returns from, or exits, the scope
// a case is registered in (a suite callback, or the module) means every registration after it never happens on
// that host, so Testing must not count those cases as evidence there (hosting/F29, hosting/F40).
//
// This file is RED by design. No suite, lane or script names it, so required CI does not run it; run it by hand:
//
//   npm run build -w @kaihacksai/kaal-hosting
//   node --test packages/kaal-hosting/06-defects/guard-before-registrations.red.mjs
//
// hosting/D12 is answered when hosting/T235 to hosting/T237 pass, unmodified, with hosting/T238 still passing.
// Do not edit this file to pass.
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { portability } from "../dist/skills/kaal-hosting/scripts/boundary-core.js";

/** The `challenged` cases of `portability` over one test source in a temporary capability. */
async function challenged(body) {
  const root = mkdtempSync(join(tmpdir(), "hosting-d12-"));
  try {
    mkdirSync(join(root, "test"));
    writeFileSync(join(root, "package.json"), JSON.stringify({ name: "capability", version: "1.0.0" }));
    writeFileSync(join(root, "test", "a.test.mjs"), `import { describe, it } from "node:test";\n${body}\n`);
    return (await portability({ name: "capability", root, builtins: ["node:test"] })).challenged;
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

test("hosting/T235: a platform guard that returns from a suite callback challenges the cases registered after it", async () => {
  const r = await challenged('describe("suite", () => {\n  if (process.platform === "win32") return;\n  it("one", () => {});\n  it("two", () => {});\n});');
  assert.deepEqual([...r].sort(), ["one", "two"]);
});

test("hosting/T236: a platform guard written as a block challenges the cases registered after it", async () => {
  const r = await challenged('describe("suite", () => {\n  if (process.platform === "win32") {\n    return;\n  }\n  it("one", () => {});\n});');
  assert.deepEqual(r, ["one"]);
});

test("hosting/T237: a platform guard that exits the module challenges the cases registered after it", async () => {
  const r = await challenged('if (process.platform === "win32") process.exit(0);\nit("one", () => {});');
  assert.deepEqual(r, ["one"]);
});

test("hosting/T238 control: a case registered before the guard is not challenged", async () => {
  const r = await challenged('describe("suite", () => {\n  it("before", () => {});\n  if (process.platform === "win32") return;\n  it("after", () => {});\n});');
  assert.ok(!r.includes("before"));
});
