// hosting/T270 and hosting/T271: Hosting's own tests do not import KAAL's Engineering, and still assert Hosting's own contract.
//
// hosting/T270 is a Test Case in its RED role for hosting/D21: it fails on 251e814 (main, where release-record.test.mjs and
// dependency-successors.test.mjs import engineering/release/release.mjs and re-judge release readiness and the verification record) and must
// pass, unmodified, in the Change that fixes it. hosting/T271 is a Test Case that passes before and after, behavior that already works and must
// keep working: the package declares exactly the five runtime dependency versions of hosting/F15. Both are ordinary Test Cases with their own
// permanent identities; RED is a role until the fix lands.
//
// This file is RED by design. No suite, lane or script names it, so required CI does not run it; run it by hand:
//
//   node --test packages/kaal-hosting/06-defects/no-engineering-import.red.mjs
//
// hosting/D21 is answered when hosting/T270 passes, unmodified, with hosting/T271 still passing.
// Do not edit this file to pass.
import assert from "node:assert/strict";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

const PACKAGE = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Every .mjs, .js and .ts file under one folder of the package. */
function sources(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return name === "node_modules" ? [] : sources(path);
    return /\.(mjs|js|ts)$/.test(name) ? [path] : [];
  });
}

test("hosting/T270: no Hosting test imports a file of KAAL's engineering directory", () => {
  const importing = sources(join(PACKAGE, "04-test")).filter((file) =>
    /\bfrom\s*["'][^"']*\/engineering\/[^"']*["']|\bimport\s*\(\s*["'][^"']*\/engineering\/[^"']*["']/.test(readFileSync(file, "utf8")));
  assert.deepEqual(importing.map((file) => relative(PACKAGE, file)), []);
});

test("hosting/T271: the package declares exactly the five runtime dependency versions of hosting/F15", () => {
  const manifest = JSON.parse(readFileSync(join(PACKAGE, "package.json"), "utf8"));
  assert.deepEqual(manifest.dependencies, {
    "cross-spawn": "7.0.6", "es-module-lexer": "3.0.3", "graceful-fs": "4.2.11", "proper-lockfile": "4.1.2", typescript: "5.9.3",
  });
});
