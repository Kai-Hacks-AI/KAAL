// hosting/T266 and hosting/T267: the coupling audit follows a platform name destructured from process with a default value.
//
// hosting/T266 is a Test Case in its RED role for hosting/D19: it fails on 2e45a5e (Hosting 0.0.1 on main, where
// `const { platform = "unknown" } = process` is not read as the platform query, so neither it nor the later use of `platform` is found)
// and must pass, unmodified, in the Change that fixes it. hosting/T267 is a Test Case that passes before and after, behavior that
// already works and must keep working: the same destructuring without a default is found, with its later use. Both are ordinary
// Test Cases with their own permanent identities; RED is a role until the fix lands. They drive the real `couplings` from the
// built package.
//
// This file is RED by design. No suite, lane or script names it, so required CI does not run it; run it by hand:
//
//   npm run build -w @kaihacksai/kaal-hosting
//   node --test packages/kaal-hosting/06-defects/destructured-platform-default.red.mjs
//
// hosting/D19 is answered when hosting/T266 passes, unmodified, with hosting/T267 still passing.
// Do not edit this file to pass.
import assert from "node:assert/strict";
import { test } from "node:test";
import { couplings } from "../dist/skills/kaal-hosting/scripts/conformance.js";

/** The lines of every platform-query finding in one source. */
async function queries(text) {
  const report = await couplings({ "src/a.mjs": Buffer.from(text) });
  return report.findings.filter((f) => f.rule === "platform-query").map((f) => f.line);
}

test("hosting/T266: a platform name destructured from process with a default is a platform query, and so is its later use", async () => {
  const r = await queries('const { platform = "unknown" } = process;\nexport const w = platform === "win32";\n');
  assert.deepEqual([...new Set(r)], [1, 2]);
});

test("hosting/T267: a platform name destructured from process without a default is a platform query, and so is its later use", async () => {
  const r = await queries('const { platform } = process;\nexport const w = platform === "win32";\n');
  assert.deepEqual([...new Set(r)], [1, 2]);
});
