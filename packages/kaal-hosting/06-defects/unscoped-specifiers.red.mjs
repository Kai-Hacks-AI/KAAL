// hosting/T108 and hosting/T109: shipped guidance names Hosting's exports by their scoped package name.
//
// hosting/T108 is the RED Case of hosting/D7. hosting/T109 is its control and passes today. The Cases read the
// package's own `exports` and every shipped Markdown file under `skills/`, `docs/` and the README. A specifier a
// reader would import must be written `@kaihacksai/kaal-hosting/<subpath>`: the unscoped legacy name is the
// legacy identity (hosting/F15). Host-fact and request identifiers such as `kaal-hosting/special-entries` are not
// export subpaths and are not matched.
//
// This file is RED by design. No suite, lane or script names it, so required CI does not run it; run it by hand
// from the repository root:
//
//   node --test packages/kaal-hosting/defects/unscoped-specifiers.red.mjs
//
// hosting/D7 is answered when hosting/T108 passes, unmodified, in the Change that corrects the guidance, with
// hosting/T109 still passing. Do not edit this file to pass.
import assert from "node:assert/strict";
import { readdirSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const subpaths = Object.keys(manifest.exports).filter((k) => k !== "." && !k.endsWith(".json")).map((k) => k.slice(2));

/** Every shipped Markdown file's path relative to the package. */
function markdown(dir) {
  const out = [];
  for (const e of readdirSync(join(root, dir), { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...markdown(p));
    else if (e.name.endsWith(".md")) out.push(p);
  }
  return out;
}
const files = [...markdown("skills"), ...markdown("docs"), "README.md"];

/** Lines naming an export subpath without the scope. */
function unscoped() {
  const hits = [];
  for (const f of files) {
    readFileSync(join(root, f), "utf8").split("\n").forEach((line, i) => {
      for (const s of subpaths) {
        const re = new RegExp(`(?<![@\\w/-])kaal-hosting/${s}(?![\\w-])`);
        if (re.test(line)) hits.push(`${f}:${i + 1} kaal-hosting/${s}`);
      }
    });
  }
  return hits;
}

test("hosting/T109 control: the package declares the export subpaths this Case checks", () => {
  assert.deepEqual(subpaths.sort(), ["boundary", "conformance", "fixtures"]);
});

test("hosting/T108 RED (hosting/D7): shipped guidance names no export subpath without the package scope", () => {
  assert.deepEqual(unscoped(), []);
});
