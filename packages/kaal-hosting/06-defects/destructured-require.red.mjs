// hosting/T104 to hosting/T107: `couplings` and a platform query bound by destructuring.
//
// hosting/T104, hosting/T105 and hosting/T106 are the RED Cases of hosting/D6. hosting/T107 is its control and
// passes today. The Cases drive the real `couplings` from the built package over one production source, whose
// platform query is written as a destructuring (hosting/F28: "through any import or destructuring" of `node:os`,
// `os`, `node:path`, `path` or `process`; hosting/F27: `.cjs` sources are read).
//
// This file is RED by design. No suite, lane or script names it, so required CI does not run it; run it by hand:
//
//   npm run build -w @kaihacksai/kaal-hosting
//   node --test packages/kaal-hosting/defects/destructured-require.red.mjs
//
// hosting/D6 is answered when hosting/T104 to hosting/T106 pass, unmodified, in the Change that fixes
// `couplings.ts`, with hosting/T107 still passing. Do not edit this file to pass.
import assert from "node:assert/strict";
import { test } from "node:test";
import { couplings } from "../dist/couplings.js";

/** The production findings `couplings` reports for one source file. */
async function found(file, source) {
  const r = await couplings({ [file]: source });
  return r.findings.filter((f) => f.scope === "production" && (f.rule === "platform-query" || f.rule === "host-api"));
}

test("hosting/T107 control: the same query as an ESM named import is a finding", async () => {
  const r = await found("lib/a.mjs", 'import { platform } from "node:os";\nexport default platform();\n');
  assert.equal(r.length > 0, true);
});

test("hosting/T104 RED (hosting/D6): a CommonJS destructured require of os.platform is a finding", async () => {
  const r = await found("lib/a.cjs", 'const { platform: host } = require("node:os");\nmodule.exports = host();\n');
  assert.equal(r.length > 0, true, "the query is a destructuring of node:os but couplings reports nothing");
});

test("hosting/T105 RED (hosting/D6): a CommonJS destructured require of path.sep is a finding", async () => {
  const r = await found("lib/a.cjs", 'const { sep } = require("node:path");\nmodule.exports = sep;\n');
  assert.equal(r.length > 0, true, "the query is a destructuring of node:path but couplings reports nothing");
});

test("hosting/T106 RED (hosting/D6): destructuring a namespace-imported os module is a finding", async () => {
  const r = await found("lib/a.mjs", 'import * as os from "node:os";\nconst { platform } = os;\nexport default platform();\n');
  assert.equal(r.length > 0, true, "the query is a destructuring of an imported os module but couplings reports nothing");
});
