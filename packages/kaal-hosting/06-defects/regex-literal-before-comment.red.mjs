// hosting/T268 and hosting/T269: the coupling audit strips comments without mistaking the end of a regular-expression literal for one.
//
// hosting/T268 is a Test Case in its RED role for hosting/D20: it fails on 2e45a5e (Hosting 0.0.1 on main, where a regular-expression literal
// that ends with an escaped slash, `/https?:\/\//`, is read as the start of a `//` comment and the rest of the line is dropped, so a platform query
// after it on the same line is not found) and must pass, unmodified, in the Change that fixes it. hosting/T269 is a Test Case that passes before and
// after, behavior that already works and must keep working: the same line with a regular expression that has no escaped slash reports the query.
// Both are ordinary Test Cases with their own permanent identities; RED is a role until the fix lands. They drive the real `couplings` from the
// built package.
//
// This file is RED by design. No suite, lane or script names it, so required CI does not run it; run it by hand:
//
//   npm run build -w @kaihacksai/kaal-hosting
//   node --test packages/kaal-hosting/06-defects/regex-literal-before-comment.red.mjs
//
// hosting/D20 is answered when hosting/T268 passes, unmodified, with hosting/T269 still passing.
// Do not edit this file to pass.
import assert from "node:assert/strict";
import { test } from "node:test";
import { couplings } from "../dist/skills/kaal-hosting/scripts/conformance.js";

/** The lines of every platform-query finding in one source. */
async function queries(text) {
  const report = await couplings({ "src/a.mjs": Buffer.from(text) });
  return report.findings.filter((f) => f.rule === "platform-query").map((f) => f.line);
}

test("hosting/T268: a platform query after a regular expression that ends with an escaped slash is found", async () => {
  const r = await queries('const isURL = /https?:\\/\\//.test(url); if (process.platform === "win32") runWindows();\n');
  assert.deepEqual(r, [1]);
});

test("hosting/T269: a platform query after a regular expression without an escaped slash is found", async () => {
  const r = await queries('const isURL = /^https:/.test(url); if (process.platform === "win32") runWindows();\n');
  assert.deepEqual(r, [1]);
});
