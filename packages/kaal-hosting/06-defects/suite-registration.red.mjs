// hosting/T227 to hosting/T231: the portability audit challenges every case a platform-conditional suite registers.
//
// hosting/T227, hosting/T228 and hosting/T229 are the RED Cases of hosting/D11: they fail on the head Codex reviewed
// (68d5b28) and must pass, unmodified, in the Change that fixes `affected` in `boundary-core.ts`. hosting/T230 and
// hosting/T231 are controls that pass before and after. The Cases drive the real `portability` from the built package
// on a capability written to a temporary directory. A case registered inside a suite that is skipped, or selected,
// by the platform is never registered on that host, so Testing must not count it as evidence there (hosting/F29,
// hosting/F40: a `registration` finding challenges the case it governs; a suite governs every case it encloses).
//
// This file is RED by design. No suite, lane or script names it, so required CI does not run it; run it by hand:
//
//   npm run build -w @kaihacksai/kaal-hosting
//   node --test packages/kaal-hosting/06-defects/suite-registration.red.mjs
//
// hosting/D11 is answered when hosting/T227 to hosting/T229 pass, unmodified, with hosting/T230 and hosting/T231
// still passing. Do not edit this file to pass.
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { portability } from "../dist/skills/kaal-hosting/scripts/boundary-core.js";

/** The `challenged` cases of `portability` over one test source in a temporary capability. */
async function challenged(body) {
  const root = mkdtempSync(join(tmpdir(), "hosting-d11-"));
  try {
    mkdirSync(join(root, "test"));
    writeFileSync(join(root, "package.json"), JSON.stringify({ name: "capability", version: "1.0.0" }));
    writeFileSync(join(root, "test", "a.test.mjs"), `import { describe, it } from "node:test";\n${body}\n`);
    return (await portability({ name: "capability", root, builtins: ["node:test"] })).challenged;
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

test("hosting/T227: a suite skipped by an option that queries the platform challenges the case it encloses", async () => {
  const r = await challenged('describe("suite", { skip: process.platform === "win32" }, () => {\n  it("child", () => {});\n});');
  assert.deepEqual(r, ["child"]);
});

test("hosting/T228: a suite selected by a platform conditional challenges the case it encloses", async () => {
  const r = await challenged('(process.platform === "win32" ? describe.skip : describe)("suite", () => {\n  it("child", () => {});\n});');
  assert.deepEqual(r, ["child"]);
});

test("hosting/T229: a platform-conditional suite challenges every case it encloses, including those in a nested suite", async () => {
  const r = await challenged('describe("outer", { skip: process.platform === "win32" }, () => {\n  it("one", () => {});\n  describe("inner", () => {\n    it("two", () => {});\n  });\n});');
  assert.deepEqual([...r].sort(), ["one", "two"]);
});

test("hosting/T230 control: a case outside the platform-conditional suite is not challenged", async () => {
  const r = await challenged('describe("suite", { skip: process.platform === "win32" }, () => {\n  it("child", () => {});\n});\nit("sibling", () => {});');
  assert.ok(!r.includes("sibling"));
});

test("hosting/T231 control: a suite with no platform condition challenges nothing", async () => {
  const r = await challenged('describe("suite", () => {\n  it("child", () => {});\n});');
  assert.deepEqual(r, []);
});
