// hosting/T264 and hosting/T265: the coupling audit reads a platform query from code, not from the text of a string.
//
// hosting/T264 is a Test Case in its RED role for hosting/D18: it fails on 2e45a5e (Hosting 0.0.1 on main, where `process.platform`
// written inside a string literal is reported as a platform query) and must pass, unmodified, in the Change that fixes it.
// hosting/T265 is a Test Case that passes before and after, behavior that already works and must keep working: a real
// `process.platform` is still a platform query. Both are ordinary Test Cases with their own permanent identities; RED is a role
// until the fix lands. They drive the real `couplings` from the built package.
//
// This file is RED by design. No suite, lane or script names it, so required CI does not run it; run it by hand:
//
//   npm run build -w @kaihacksai/kaal-hosting
//   node --test packages/kaal-hosting/06-defects/platform-query-in-string.red.mjs
//
// hosting/D18 is answered when hosting/T264 passes, unmodified, with hosting/T265 still passing.
// Do not edit this file to pass.
import assert from "node:assert/strict";
import { test } from "node:test";
import { couplings } from "../dist/skills/kaal-hosting/scripts/conformance.js";

/** The rule and line of every finding in one source. */
async function findings(text) {
  const report = await couplings({ "src/a.mjs": Buffer.from(text) });
  return report.findings.map((f) => [f.rule, f.line]);
}

test("hosting/T264: a message that only mentions process.platform is not a platform query", async () => {
  const r = await findings('throw new Error("do not read process.platform here");\n');
  assert.deepEqual(r.filter(([rule]) => rule === "platform-query"), []);
});

test("hosting/T265: a use of process.platform is a platform query", async () => {
  const r = await findings("export const w = process.platform;\n");
  assert.deepEqual(r.filter(([rule]) => rule === "platform-query"), [["platform-query", 1]]);
});
