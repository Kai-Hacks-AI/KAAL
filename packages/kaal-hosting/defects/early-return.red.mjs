// hosting/T101, hosting/T102 and hosting/T103: the portability audit and an early return that is not the first statement.
//
// hosting/T101 is the RED Case of hosting/D5. hosting/T102 and hosting/T103 are its controls and pass today.
// The Cases drive the real `portability` from the built package, on a capability written to a temporary directory:
// a test that, on Windows, does some setup and then returns before any assertion. That test asserts nothing on
// Windows, so Testing must not count it as evidence there (hosting/F29: an early `return` from a test is
// `registration`; hosting/F40: `registration` and `dilution` findings challenge the case they govern).
//
// This file is RED by design. No suite, lane or script names it, so required CI does not run it; run it by hand:
//
//   npm run build -w @kaihacksai/kaal-hosting
//   node --test packages/kaal-hosting/defects/early-return.red.mjs
//
// hosting/D5 is answered when hosting/T101 passes, unmodified, in the Change that fixes `couplings.ts`, with
// hosting/T102 and hosting/T103 still passing. Do not edit this file to pass.
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { portability } from "../dist/boundary-core.js";

/** The `challenged` cases and request ids of `portability` over one test file in a temporary capability. */
async function audit(body) {
  const root = mkdtempSync(join(tmpdir(), "hosting-d5-"));
  try {
    mkdirSync(join(root, "test"));
    writeFileSync(join(root, "package.json"), JSON.stringify({ name: "capability", version: "1.0.0" }));
    writeFileSync(join(root, "test", "a.test.mjs"), `import test from "node:test";\ntest("c1", () => {\n${body}\n  assertSomething();\n});\n`);
    const r = await portability({ name: "capability", root, builtins: ["node:test"] });
    return { challenged: r.challenged, ids: r.reviews.map((q) => q.id) };
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

test("hosting/T102 control: a platform branch whose first statement is the return challenges the case", async () => {
  const r = await audit('  if (process.platform === "win32") { return; }');
  assert.deepEqual(r.challenged, ["c1"]);
});

test("hosting/T103 control: a return inside a function declared in the branch is not an early return", async () => {
  const r = await audit('  if (process.platform === "win32") { const f = () => { return 1; }; f(); }');
  assert.deepEqual(r.challenged, []);
});

test("hosting/T101 RED (hosting/D5): a return after other statements in the platform branch challenges the case", async () => {
  const r = await audit('  if (process.platform === "win32") { cleanup(); return; }');
  assert.deepEqual(r.challenged, ["c1"], "the test returns before any assertion on win32 but the audit does not challenge it");
});
