#!/usr/bin/env node
// compare --skills-ref <command> [--spec <specification.mdx>] [--write]
//
// Re-observes both validators on the shared fixtures and on the packaged
// Engineer Skill: KAAL's checkSkill, as check-skill reaches it, and the
// reference validator, skills-ref, run as `<command> validate <dir>`. Each
// observed verdict is compared with the one recorded in cases.mjs. With
// --write, the observations are written to results.md next to this file;
// --spec records the SHA-256 of the specification text compared against.
//
// skills-ref is evidence, not a dependency: nothing in the package or its
// tests needs it. Exits 0 when every observation matches its record, 1 when
// one does not, 2 on misuse.
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execute } from "kaal-hosting";
import { CASES, PACKAGED, SECTIONS, SPEC } from "./cases.mjs";
import { kaal, materialize } from "./fixtures.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const PACKAGE = resolve(HERE, "../..");

function options(argv) {
  const o = { write: false };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--write") o.write = true;
    else if (argv[i] === "--skills-ref" && argv[i + 1]) o.skillsRef = argv[++i];
    else if (argv[i] === "--spec" && argv[i + 1]) o.spec = argv[++i];
    else return undefined;
  }
  return o.skillsRef ? o : undefined;
}

async function skillsRef(command, dir, root) {
  const r = await execute(command, ["validate", dir], { cwd: root });
  const messages = r.stderr.split("\n").filter((l) => l.startsWith("  - ")).map((l) => l.slice(4).split(root).join("<fixtures>"));
  return { verdict: r.status === 0 ? "ok" : "fail", messages };
}

const cell = (s) => s.replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/\n/g, " ");

async function main(argv) {
  const o = options(argv);
  if (!o) {
    console.error("usage: compare --skills-ref <command> [--spec <specification.mdx>] [--write]");
    return 2;
  }
  const version = (await execute(o.skillsRef, ["--version"], { cwd: HERE })).stdout.trim();
  const root = mkdtempSync(join(tmpdir(), "kaal-conformance-"));
  const rows = [];
  for (const { case: c, dir } of await materialize(root)) {
    rows.push({ c, kaal: await kaal(dir, c.dir ?? "my-skill"), ref: await skillsRef(o.skillsRef, dir, root) });
  }
  const own = join(PACKAGE, PACKAGED.path);
  const packaged = { kaal: await kaal(own, "kaal-engineer-skill"), ref: await skillsRef(o.skillsRef, own, PACKAGE) };

  const mismatches = [];
  for (const { c, kaal: k, ref } of rows) {
    if (k.verdict !== c.kaal) mismatches.push(`${c.id}: KAAL recorded ${c.kaal}, observed ${k.verdict}`);
    if (ref.verdict !== c.skillsRef) mismatches.push(`${c.id}: skills-ref recorded ${c.skillsRef}, observed ${ref.verdict}`);
  }
  if (packaged.kaal.verdict !== PACKAGED.kaal) mismatches.push(`packaged: KAAL recorded ${PACKAGED.kaal}, observed ${packaged.kaal.verdict}`);
  if (packaged.ref.verdict !== PACKAGED.skillsRef) mismatches.push(`packaged: skills-ref recorded ${PACKAGED.skillsRef}, observed ${packaged.ref.verdict}`);

  const pkg = JSON.parse(readFileSync(join(PACKAGE, "package.json"), "utf8"));
  const out = [
    "# Conformance results",
    "",
    "Generated by `test/conformance/compare.mjs --write`. Do not edit by hand.",
    "",
    `- Specification: ${SPEC}${o.spec ? `, text SHA-256 \`${createHash("sha256").update(readFileSync(o.spec)).digest("hex")}\`` : ""}`,
    `- Reference validator: skills-ref ${version.replace(/^.*version\s*/i, "")}`,
    `- KAAL: kaal-engineer-skill ${pkg.version} (yaml ${pkg.dependencies.yaml}, commonmark ${pkg.dependencies.commonmark})`,
    `- Cases: ${rows.length}, observations matching their record: ${mismatches.length === 0 ? "all" : `${2 * rows.length + 2 - mismatches.length} of ${2 * rows.length + 2}`}`,
    "",
    "## The packaged Engineer Skill",
    "",
    "| Skill | Specification | KAAL | skills-ref |",
    "|---|---|---|---|",
    `| \`${PACKAGED.path}\` | ${PACKAGED.spec} | ${packaged.kaal.verdict} | ${packaged.ref.verdict} |`,
    "",
    "## Fixtures",
    "",
    "| Case | Section | Specification | KAAL | skills-ref | Class | KAAL findings | skills-ref findings |",
    "|---|---|---|---|---|---|---|---|",
    ...rows.map(({ c, kaal: k, ref }) =>
      `| \`${c.id}\`: ${cell(c.title)} | [${SECTIONS[c.section]}](${SPEC}#${c.section}) | ${c.spec} | ${k.verdict} | ${ref.verdict} | ${c.class ?? ""} | ${cell(k.messages.join("; "))} | ${cell(ref.messages.join("; "))} |`,
    ),
    "",
  ].join("\n");
  if (o.write) writeFileSync(join(HERE, "results.md"), out);
  else console.log(out);
  for (const m of mismatches) console.error(`mismatch: ${m}`);
  return mismatches.length > 0 ? 1 : 0;
}

process.exitCode = await main(process.argv.slice(2));
