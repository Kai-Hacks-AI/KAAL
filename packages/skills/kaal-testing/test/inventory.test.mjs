import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { inventory, loc } from "kaal-testing/inventory";

const text = (s) => new TextEncoder().encode(s);

describe("lines of code", () => {
  it("counts lines with any non-whitespace character, whatever the line endings", () => {
    assert.equal(loc(text("a\n\n  \nb\n")), 2);
    assert.equal(loc(text("a\r\n\r\nb")), 2);
    assert.equal(loc(text("a\rb\r")), 2);
    assert.equal(loc(text("\t\n")), 0);
    assert.equal(loc(text("")), 0);
  });

  it("treats bytes with NUL or that are not UTF-8 as binary", () => {
    assert.equal(loc(new Uint8Array([0x61, 0x00, 0x62])), undefined);
    assert.equal(loc(new Uint8Array([0xff, 0xfe, 0x61])), undefined);
  });
});

describe("the inventory", () => {
  const result = inventory([
    { path: "src/b.js", bytes: text("x\n\ny\n") },
    { path: "README.md", bytes: text("# r\n") },
    { path: "logo.png", bytes: new Uint8Array([0x89, 0x50, 0x00]) },
    { path: "package-lock.json", bytes: text("{\n}\n") },
    { path: "packages/p/package-lock.json", bytes: text("{}\n") },
  ]);

  it("lists every file once, sorted, with how it was counted", () => {
    assert.deepEqual(result.entries, [
      { path: "README.md", kind: "text", loc: 1 },
      { path: "logo.png", kind: "binary", loc: 0 },
      { path: "package-lock.json", kind: "excluded", loc: 2, reason: "generated by npm" },
      { path: "packages/p/package-lock.json", kind: "excluded", loc: 1, reason: "generated by npm" },
      { path: "src/b.js", kind: "text", loc: 2 },
    ]);
  });

  it("totals text files only, and keeps what is excluded visible beside it", () => {
    assert.deepEqual(
      { files: result.files, text: result.text, binary: result.binary, loc: result.loc, excluded: result.excluded },
      { files: 5, text: 2, binary: 1, loc: 3, excluded: { files: 2, loc: 3 } },
    );
    assert.equal(result.loc, result.entries.filter((e) => e.kind === "text").reduce((n, e) => n + e.loc, 0));
  });
});
