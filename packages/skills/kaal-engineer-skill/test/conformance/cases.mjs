// The shared conformance fixtures: representative Agent Skills, each tied to
// the section of the Agent Skills specification it exercises, with the
// verdict the specification gives and the verdicts both validators were
// observed to give.
//
// Each case is a skill directory: `dir` is its name (default "my-skill") and
// `files` its contents, keyed by "/"-separated relative path. The same bytes
// are handed to KAAL's validator and to the reference validator, skills-ref.
//
//   spec       accept | reject | open: what the specification decides. "open"
//              means its text does not settle the case; `why` says how.
//   kaal       KAAL's observed verdict: ok, warning, or the kinds of its
//              findings joined by "+" (standard, kaal).
//   skillsRef  skills-ref's observed verdict: ok or fail.
//   class      set exactly when the verdicts differ from each other or from
//              the specification:
//                specification-violation  KAAL accepts what the specification
//                                         prohibits, or rejects what it
//                                         requires accepting
//                kaal-rule                a KAAL engineering rule beyond the
//                                         specification
//                advisory                 guidance, not mandatory conformance
//                reference-difference     the implementations differ where the
//                                         specification sets no definitive
//                                         requirement, or skills-ref departs
//                                         from one KAAL follows
//
// test/conformance.test.mjs checks the KAAL verdicts on every run. compare.mjs
// re-observes both validators and writes results.md.

