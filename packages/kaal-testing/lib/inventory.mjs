// The repository's non-blank text lines: an inventory of every file the caller
// lists, with how each was counted. Which files exist is the caller's answer;
// this decides only how they count. The metric is deliberately broad: a
// non-blank text line is any line with at least one non-whitespace character
// in any text file, whether code, Markdown, YAML, JSON or configuration. It is
// not executable lines of code, and is never a denominator for coverage. A file
// whose bytes contain NUL or are not UTF-8 is binary: it is listed and has no
// text lines. A file matching an exclusion is listed with its reason, counted,
// and kept out of the total.

/** Files kept out of the total, each with the reason it is. */
export const EXCLUDED = [{ pattern: /(^|\/)package-lock\.json$/, reason: "generated by npm" }];

const utf8 = new TextDecoder("utf-8", { fatal: true });

/** Lines with at least one non-whitespace character, or undefined when `bytes` is not text. */
export function textLines(bytes) {
  if (bytes.includes(0)) return undefined;
  let text;
  try {
    text = utf8.decode(bytes);
  } catch {
    return undefined;
  }
  return text.split(/\r\n|\n|\r/).filter((line) => line.trim() !== "").length;
}

/**
 * The inventory of `files`, an array of { path, bytes } with `/`-separated
 * repository-relative paths. Resolves each to { path, kind, lines, reason? },
 * kind being "text", "binary" or "excluded", sorted by path, with totals:
 * `lines` is the sum over text files only, and `excluded` sums what was kept
 * out.
 */
export function inventory(files) {
  const entries = files
    .map(({ path, bytes }) => {
      const lines = textLines(bytes);
      const exclusion = EXCLUDED.find(({ pattern }) => pattern.test(path));
      if (lines === undefined) return { path, kind: "binary", lines: 0 };
      if (exclusion) return { path, kind: "excluded", lines, reason: exclusion.reason };
      return { path, kind: "text", lines };
    })
    .sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  const sum = (kind) => entries.filter((e) => e.kind === kind).reduce((n, e) => n + e.lines, 0);
  const count = (kind) => entries.filter((e) => e.kind === kind).length;
  return {
    metric: "non-blank text lines",
    files: entries.length,
    text: count("text"),
    binary: count("binary"),
    lines: sum("text"),
    excluded: { files: count("excluded"), lines: sum("excluded") },
    entries,
  };
}
