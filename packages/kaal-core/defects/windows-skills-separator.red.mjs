// core/T124: Core's identity test must not test a directory entry's path against a "/"-separated fragment.
//
// Identities in this file, one per leaf test: core/T124 is the RED Case of core/D3. core/T125 is its control (passes
// today): it shows that the entries `readdirSync(..., { recursive: true })` returns use the host separator, so on
// Windows a "/skills/" test never matches and the Skill files, which are not typed Nodes, reach the identity check.
//
// Found by the Windows full-suite run on the core/D1 and core/D2 fix (#1025): 180 of 181 pass; the identity test
// fails with "object null is not iterable" at the line that reads the first Skill file as a Node.
// The Case reads the test file as text, so it is RED on any host, not only on Windows.
//
// This file is RED by design. No suite, lane or script names it, so required CI does not run it; run it by hand:
//
//   node --test defects/windows-skills-separator.red.mjs        (from packages/kaal-core)
//
// core/D3 is answered when core/T124 passes, unmodified, in the Change that fixes the line, with core/T125 still
// passing and the Windows full suite green. Do not edit this file to pass.
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";
import { win32 } from "node:path";

const CORE = new URL("../", import.meta.url);
const source = (path) => readFileSync(new URL(path, CORE), "utf8");
/** Lines that test a directory entry against a "/"-separated fragment, which a Windows entry never contains. */
const fragments = (text) =>
  text
    .split("\n")
    .map((line, i) => ({ line: i + 1, text: line }))
    .filter((l) => /\.includes\(\s*["'`]\/[^"'`]*\/["'`]\s*\)/.test(l.text) && !l.text.trim().startsWith("//"));

test("core/T125 control: a Windows directory entry uses backslashes, so a '/skills/' test never matches it", () => {
  const entry = win32.join("kaal-core", "skills", "kaal-core", "SKILL.md");
  assert.equal(entry, "kaal-core\\skills\\kaal-core\\SKILL.md");
  assert.equal(entry.includes("/skills/"), false);
  assert.equal(entry.split(win32.sep).includes("skills"), true);
});

test("core/T124 RED (core/D3): test/core.test.ts tests no directory entry against a '/'-separated fragment", () => {
  const found = fragments(source("test/core.test.ts"));
  assert.deepEqual(found, [], `test/core.test.ts tests a path against a "/" fragment; split it on the separator instead:\n${found.map((l) => `  line ${l.line}: ${l.text.trim()}`).join("\n")}`);
});
