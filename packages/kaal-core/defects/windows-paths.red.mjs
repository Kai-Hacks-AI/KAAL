// core/T121 and core/T122: Core's own tests must not build a host path from a file URL's `pathname`.
//
// Identities in this file, one per leaf test: core/T121 is the RED Case of core/D1 and core/T122 the RED Case of
// core/D2. core/T123 is their control (passes today): it shows why `pathname` is wrong on Windows and what is right.
//
// On Windows `new URL("file:///D:/a/x/").pathname` is "/D:/a/x/", which is not a Windows path: joined or sliced as one
// it gives "D:\D:\a\x" or drops the first letter of the next segment. Node's `fileURLToPath` is the conversion.
// The Cases read the two test files as text, so they are RED on any host, not only on Windows.
//
// This file is RED by design. No suite, lane or script names it, so required CI does not run it; run it by hand:
//
//   node --test defects/windows-paths.red.mjs        (from packages/kaal-core)
//
// core/D1 and core/D2 are answered when core/T121 and core/T122 pass, unmodified, in the Change that fixes the two
// files, with core/T123 still passing. Do not edit this file to pass.
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import { win32 } from "node:path";

const CORE = new URL("../", import.meta.url);
const source = (path) => readFileSync(new URL(path, CORE), "utf8");
/** Lines that read a file URL's pathname, which is not a host path. */
const pathnames = (text) => text.split("\n").map((line, i) => ({ line: i + 1, text: line })).filter((l) => /\.pathname\b/.test(l.text) && !l.text.trim().startsWith("//"));

test("core/T123 control: a Windows file URL's pathname is not a Windows path, and fileURLToPath is", () => {
  const url = new URL("file:///D:/a/KAAL/KAAL/packages/kaal-core/dist-test/core.test.js");
  assert.equal(url.pathname, "/D:/a/KAAL/KAAL/packages/kaal-core/dist-test/core.test.js");
  assert.equal(fileURLToPath(url, { windows: true }), "D:\\a\\KAAL\\KAAL\\packages\\kaal-core\\dist-test\\core.test.js");
  // The two faults: a drive letter doubled when the pathname is joined onto a root, and the first letter lost when its length is sliced off a real path.
  assert.equal(win32.join("D:\\", url.pathname), "D:\\D:\\a\\KAAL\\KAAL\\packages\\kaal-core\\dist-test\\core.test.js");
  assert.equal("D:\\a\\KAAL\\KAAL\\packages\\kaal-core\\src".slice(new URL("file:///D:/a/KAAL/KAAL/packages/kaal-core/").pathname.length), "rc");
});

test("core/T121 RED (core/D1): test/core.test.ts builds no host path from a file URL's pathname", () => {
  const found = pathnames(source("test/core.test.ts"));
  assert.deepEqual(found, [], `test/core.test.ts reads URL.pathname as a path; use fileURLToPath:\n${found.map((l) => `  line ${l.line}: ${l.text.trim()}`).join("\n")}`);
});

test("core/T122 RED (core/D2): test/plan/love.test.mjs builds no host path from a file URL's pathname", () => {
  const found = pathnames(source("test/plan/love.test.mjs"));
  assert.deepEqual(found, [], `test/plan/love.test.mjs reads URL.pathname as a path; use fileURLToPath:\n${found.map((l) => `  line ${l.line}: ${l.text.trim()}`).join("\n")}`);
});
