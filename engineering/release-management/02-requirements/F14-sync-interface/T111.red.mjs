// Case release/T111 tests: F14
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
const repo = fileURLToPath(import.meta.url).split('/engineering/')[0];
const cap = join(repo, 'engineering/release-management');
const template = join(repo, '.github/PULL_REQUEST_TEMPLATE/sync.md');
const read = (path, what) => { assert.ok(existsSync(path), `${what} is absent`); return readFileSync(path, 'utf8'); };
const headings = (text) => text.split('\n').filter((line) => line.startsWith('## ')).map((line) => line.slice(3).trim());
export const id = 'release/T111';
export const tests = ['release/F14'];
export const title = 'the interface of F14 accepts its worked body and rejects the shapes seen on SYNC pull requests: PLAN chapters, a footer, a Change line without an identity, a restated source, an empty reason';
const chapter = (text, name) => (text.split(new RegExp(`^## ${name}$`, 'm'))[1] ?? '').split(/^## /m)[0].trim();
const problems = (body) => {
  const found = [];
  if (JSON.stringify(headings(body)) !== JSON.stringify(['Change', 'Reason'])) found.push('chapters');
  if (!/^[a-z-]+\/C\d+ [^:\n]+$/.test(chapter(body, 'Change'))) found.push('Change line');
  const reason = chapter(body, 'Reason');
  if (reason === '' || /\n\s*\n/.test(reason)) found.push('Reason');
  if (/Generated with|claude\.ai|Requested by|claude-projects-attribution|^---$/m.test(body)) found.push('contamination');
  return found;
};
export function run() {
  read(join(cap, '02-requirements/F14-sync-interface/F14.md'), 'F14');
  const example = read(join(cap, '02-requirements/F14-sync-interface/example.md'), 'the worked body');
  assert.deepEqual(problems(example), [], 'the worked body is rejected');
  const planShaped = '## Change\n\nSynchronization: bring main into the collector kaal/release/do-template.\n\n## From\n\nThe collector is behind main.\n\n## To\n\nThe collector contains main. Its own files are unchanged.\n\n## Because\n\nThe promotion #1427 can then be judged again.';
  assert.ok(problems(planShaped).includes('chapters'), 'a PLAN-shaped body is accepted');
  assert.ok(problems(example + '\n---\n_Generated by Claude Code_').includes('contamination'), 'a footed body is accepted');
  assert.ok(problems(example.replace('release/C7 do template', 'the do template')).includes('Change line'), 'a Change line without an identity is accepted');
  assert.ok(problems(example.replace('## Reason', '## Sync\n\nmain d19abef into kaal/release/do-template\n\n## Reason')).includes('chapters'), 'a restated source is accepted');
  assert.ok(problems(example.replace(/(## Reason\n\n).*/, '$1')).includes('Reason'), 'an empty reason is accepted');
}
