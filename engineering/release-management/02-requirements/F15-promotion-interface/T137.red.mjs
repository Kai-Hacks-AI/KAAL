// Case release/T137 tests: F15
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
const repo = fileURLToPath(import.meta.url).split('/engineering/')[0];
const cap = join(repo, 'engineering/release-management');
const template = join(repo, '.github/PULL_REQUEST_TEMPLATE/promotion.md');
const planTemplate = join(repo, '.github/PULL_REQUEST_TEMPLATE/plan.md');
const read = (path, what) => { assert.ok(existsSync(path), `${what} is absent`); return readFileSync(path, 'utf8'); };
const headings = (text) => text.split('\n').filter((line) => line.startsWith('## ')).map((line) => line.slice(3).trim());
export const id = 'release/T137';
export const tests = ['release/F15'];
export const title = 'a promotion body of the three chapters passes, and the bodies seen on promotions (PLAN headings, test and approval status, a merge method, a footer) are rejected';
// The judgement of F15 on a body, written as the Case's own reading of the requirement. It reads a body as written, so a hidden comment before the first chapter counts as text before it.
function judge(body) {
  const found = [];
  const chapters = headings(body);
  if (chapters.join('|') !== 'Collector|Delivers|Order') found.push('chapters');
  if (body.split(/^## /m)[0].trim() !== '') found.push('text before the first chapter');
  if (/^---$|Generated with|claude\.ai\/code|Requested by|claude-projects-attribution/m.test(body)) found.push('attribution or footer');
  if (/\b(squash|merge commit|rebase)\b/i.test(body)) found.push('merge method');
  if (/\b(approv|CPO|green|passed|verified)/i.test(body)) found.push('approval or check status');
  return found;
}
export function run() {
  const clean = '## Collector\n\nkaal/release/do-template → main, release management\n\n## Delivers\n\nrelease/C7 PLAN: do template\nrelease/C7 DO: do template Cases\n\n## Order\n\nWith #1428. After the synchronization of the collector with main.\n';
  assert.deepEqual(judge(clean), [], 'a clean promotion body is rejected');
  const observed1403 = '## Intent\n\nPromote the collector into main.\n\n## Design\n\nNo design.\n\n## Verified by\n\nThe checks of #1401.\n\n## Validated by\n\nExact-head CPO approval of #1401.\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_x)_\n';
  assert.ok(judge(observed1403).includes('chapters'), 'the Intent, Design, Verified by, Validated by body is accepted');
  assert.ok(judge(observed1403).includes('attribution or footer'), 'a generated footer is accepted');
  const planShaped = '## Change\n\nrelease/C8 check PR Body.\n\n## From\n\nmain has no check.\n\n## To\n\nmain holds a check.\n\n## Because\n\nReviewers stop correcting bodies.\n';
  assert.ok(judge(planShaped).includes('chapters'), 'a PLAN-shaped body is accepted');
  assert.ok(judge(clean.replace('none', 'x') + '\nMerge commit.\n').includes('merge method'), 'a stated merge method is accepted');
  assert.ok(judge(clean + '\nExact-head CPO approval of the Changes.\n').includes('approval or check status'), 'a stated approval is accepted');
  read(template, 'the promotion template');
}
